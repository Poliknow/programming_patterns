def hw_01(total_seconds):
    """Секунды в строку «ЧЧ:ММ:СС».

    Верните время в виде строки "ЧЧ:ММ:СС" с ведущими нулями
    (например, 1 час 1 минута 1 секунда — "01:01:01").

    Примеры:
        hw_01(3661) == "01:01:01"
        hw_01(59) == "00:00:59"
        hw_01(0) == "00:00:00"
        hw_01(3600) == "01:00:00"
        hw_01(86399) == "23:59:59"
    """
    hours = total_seconds // 3600
    remaining_seconds = total_seconds % 3600
    minutes = remaining_seconds // 60
    seconds = remaining_seconds % 60

    return f"{hours:02d}:{minutes:02d}:{seconds:02d}"


def hw_02(a, b, c):
    """Площадь треугольника по формуле Герона.

    a, b, c — стороны треугольника. Верните площадь, округлённую
    до двух знаков после точки.

    Примеры:
        hw_02(3, 4, 5) == 6.0
        hw_02(5, 5, 6) == 12.0
        hw_02(1, 1, 1.4142135623730951) == 0.5
    """
    # Полупериметр
    s = (a + b + c) / 2

    # Площадь по формуле Герона
    area = (s * (s - a) * (s - b) * (s - c)) ** 0.5

    return round(area, 2)


def hw_03(card_number):
    """Маскировка номера карты.

    card_number — строка цифр длиной не менее 4. Замените все символы,
    кроме последних четырёх, на "*", и верните результат.

    Примеры:
        hw_03("1234567812345678") == "************5678"
        hw_03("1234") == "1234"
        hw_03("987210") == "**7210"
    """
    if len(card_number) <= 4:
        return card_number

    # Заменяем все символы кроме последних 4 на "*"
    return "*" * (len(card_number) - 4) + card_number[-4:]


def hw_04(x, y):
    """Отчёт о делении.

    Верните строку вида "x / y = частное", где частное отформатировано
    с двумя знаками после точки (например, "2.50").

    Примеры:
        hw_04(7, 3) == "7 / 3 = 2.33"
        hw_04(10, 4) == "10 / 4 = 2.50"
        hw_04(1, 2) == "1 / 2 = 0.50"
    """
    result = x / y
    return f"{x} / {y} = {result:.2f}"